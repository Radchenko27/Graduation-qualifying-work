"""
Демонстрация изменений в парсере спецификаций.
Показывает разницу между старым и новым форматом JSON.
"""

from app.utils.specification_parser import SpecificationParser

p = object.__new__(SpecificationParser)
p._use_pdf_fallback = False

# Тестовые данные: две страницы с РАЗНЫМИ заголовками
text_page_2 = """СПЕЦИФИКАЦИЯ ОБОРУДОВАНИЯ

Позиция  Обозначение  Наименование              Кол-во  Ед.изм.
1        Э1.00.00.000 Электродвигатель АИР80А2  2       шт.
2        К1.00.00.000 Контактор КМИ-10910       4       шт.
"""

text_page_3 = """ПРОДОЛЖЕНИЕ СПЕЦИФИКАЦИИ

№ п/п    Марка        Тип                       Количество Единица Примечание
3        Р1.00.00.000 Реле РЭК77/3               10         шт.     Резерв
4        В1.00.00.000 Выключатель автоматический 6          шт.
"""

print("=" * 70)
print("ДЕМОНСТРАЦИЯ НОВОГО АЛГОРИТМА ПАРСИНГА")
print("=" * 70)

# Парсим страницу 2
table_2 = p._parse_page_by_columns(text_page_2, 2, 0.95)
print("\n📄 СТРАНИЦА 2:")
print(f"   Заголовок: {table_2['header']!r}")
print(f"   Метод: {table_2['parse_method']}")
print("   Столбцы (columns):")
for col in table_2['columns']:
    print(f"      {col['label']!r:20} -> key={col['key']!r:15} start={col['start']:3} end={col['end']}")

# Парсим страницу 3
table_3 = p._parse_page_by_columns(text_page_3, 3, 0.92)
print("\n📄 СТРАНИЦА 3:")
print(f"   Заголовок: {table_3['header']!r}")
print(f"   Метод: {table_3['parse_method']}")
print("   Столбцы (columns):")
for col in table_3['columns']:
    print(f"      {col['label']!r:20} -> key={col['key']!r:15} start={col['start']:3} end={col['end']}")

print("\n" + "=" * 70)
print("КЛЮЧЕВЫЕ ИЗМЕНЕНИЯ:")
print("=" * 70)

print("""
1. ЗАГОЛОВКИ ОПРЕДЕЛЯЮТСЯ ПО СТРАНИЧНО
   Старый алгоритм: использовал фиксированный список колонок для ВСЕХ страниц
   Новый алгоритм:  каждая страница имеет СВОЙ набор columns[]

   Страница 2: ['Позиция', 'Обозначение', 'Наименование', 'Кол-во', 'Ед.изм.']
   Страница 3: ['№ п/п', 'Марка', 'Тип', 'Количество', 'Единица', 'Примечание']

2. ВЫХОДНОЙ JSON — ТЕПЕРЬ С ОРИГИНАЛЬНЫМИ НАЗВАНИЯМИ
   Старый формат (all_rows_flat):
     {"position": "3", "name": "Реле РЭК77/3", "quantity": "10", ...}
   
   Новый формат (all_rows_flat):
     {"№ п/п": "3", "Марка": "Р1.00.00.000", "Тип": "Реле РЭК77/3",
      "Количество": "10", "Единица": "шт.", "Примечание": "Резерв"}
   
   → Ключи = исходные русские названия из заголовка страницы!
     Это позволяет редактировать файл и понимать, что есть что.

3. СТРУККТУРА specifications В JSON:
   Каждая страница содержит:
   - header          — текст найденной строки заголовка
   - columns[]       — метаданные каждой колонки (key, label, start, end)
   - rows[]          — строки с cells_by_header (маппинг по оригинальным label)
   - parse_method    — "fixed_width_by_page_header"
""")

print("=" * 70)
print("ДЕМО Excel-экспорта:")
print("=" * 70)

df_2 = p._table_to_dataframe(table_2)
df_3 = p._table_to_dataframe(table_3)

print("\nЛист 'Стр_2' (заголовки из оригинального заголовка страницы 2):")
print(df_2.to_string(index=False))

print("\nЛист 'Стр_3' (заголовки из оригинального заголовка страницы 3):")
print(df_3.to_string(index=False))

print("\n✅ Демонстрация завершена!")
